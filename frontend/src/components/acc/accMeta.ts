/* 衣冠皮层共用的小工具：卡片编号补零 + 按大类取视觉区底色。
   底色取自子站卡片 tone 一族（暖褐 / 石青 / 绛紫 / 松绿…），只作 16–30% 淡染。 */

export function pad(n: number) {
  return String(n).padStart(2, "0");
}

