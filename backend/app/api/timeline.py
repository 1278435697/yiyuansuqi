@router.get("/timeline")
def timeline(db: Session = Depends(get_db)):
    """时间轴主数据：阶段 + 该朝代档案/文物数量。"""
    costume_counts = dict(
        db.query(Costumes.dynasty, func.count(Costumes.id)).group_by(Costumes.dynasty).all()
    )
    relic_counts = dict(
        db.query(Relics.dynasty, func.count(Relics.id)).group_by(Relics.dynasty).all()
    )
    return {
        "stages": [{
            **s,
            "costume_count": costume_counts.get(s["dynasty"], 0),
            "relic_count": relic_counts.get(s["dynasty"], 0),
        } for s in TIMELINE_STAGES],
    }


@router.get("/timeline/{dynasty}")
def timeline_detail(dynasty: str, db: Session = Depends(get_db)):
    costumes = db.query(Costumes).filter_by(dynasty=dynasty).all()
    relics = db.query(Relics).filter_by(dynasty=dynasty).all()
    stage = next((s for s in TIMELINE_STAGES if s["dynasty"] == dynasty), None)
    return {
        "stage": stage,
        "costumes": [{
            "id": c.id, "name": c.name, "category": c.category,
            "wearer": c.wearer, "source_type": c.source_type,
            "fabric": c.fabric, "pattern": c.pattern, "color": c.color,
            "description": c.description or "",
        } for c in costumes],
        "relics": [{
            "id": r.id, "name": r.name, "location": r.location,
            "museum": r.museum, "image_url": r.image_url,
            "description": r.description or "",
        } for r in relics],
    }
