const { spawn } = require('child_process');
const sleep = ms => new Promise(r => setTimeout(r, ms));
(async () => {
  const port = Number(process.env.PORT || 9640);
  const base = process.argv[2] || 'http://localhost:5173';
  const child = spawn('C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',
    ['--headless=new','--disable-gpu','--no-sandbox',`--remote-debugging-port=${port}`,'--user-data-dir='+require('os').tmpdir()+'/ysmx'+port,'about:blank'], { stdio:'ignore' });
  let ws;
  for (let i=0;i<60;i++){ try{ const l=await (await fetch(`http://127.0.0.1:${port}/json/list`)).json();
    const t=l.find(x=>x.type==='page'); if(!t) throw 0; ws=new WebSocket(t.webSocketDebuggerUrl);
    await new Promise((res,rej)=>{ws.onopen=res;ws.onerror=rej}); break;}catch{await sleep(250);} }
  let id=0; const p={}; ws.onmessage=e=>{const mm=JSON.parse(e.data); if(p[mm.id]){p[mm.id](mm);delete p[mm.id];}};
  const send=(method,params)=>new Promise(r=>{const i=++id;p[i]=r;ws.send(JSON.stringify({id:i,method,params}));});
  const ev=async e=>{const r=await send('Runtime.evaluate',{expression:e,returnByValue:true});
    const ed=r.result.exceptionDetails; if(ed)return 'ERR '+(ed.exception&&ed.exception.description?ed.exception.description.split('\n')[0]:ed.text);
    return r.result.result.value;};
  const V = `(function(){var v=document.querySelector('.el-image-viewer__wrapper');if(!v)return 'CLOSED';
    var nx=v.querySelector('.el-image-viewer__next');var im=v.querySelector('.el-image-viewer__img');
    return 'OPEN imgs='+v.querySelectorAll('.el-image-viewer__img').length+' 右箭头='+(nx?'有':'无')+' 当前='+(im?im.src.slice(-14):'-');})()`;
  const close=async()=>{await ev(`(function(){var b=document.querySelector('.el-image-viewer__close');if(b)b.click();return 1})()`);await sleep(600);};
  await send('Runtime.enable',{}); await send('Page.enable',{});
  await send('Emulation.setDeviceMetricsOverride',{width:1440,height:900,deviceScaleFactor:1,mobile:false});
  await send('Page.navigate',{url:base+'/pattern/32'}); await sleep(11000);
  console.log('### '+base);
  console.log('  .img-col 的 Vue 监听键: ' + await ev(`(function(){var c=document.querySelector('.img-col');var im=document.querySelector('.img-col img');
    return 'col._vei='+JSON.stringify(Object.keys(c._vei||{}))+' img._vei='+JSON.stringify(Object.keys(im?im._vei||{}:'no-img'))+' col.outerHTML头='+c.outerHTML.slice(0,70);})()`));
  console.log('  1) img.click()      -> ' + await ev(`(function(){var im=document.querySelector('.img-col img');im.click();return '已派发'})()`) + ' / ' + await ev(V));
  await close();
  console.log('  2) col.click()      -> ' + await ev(`(function(){document.querySelector('.img-col').click();return '已派发'})()`) + ' / ' + await ev(V));
  await close();
  const b = JSON.parse(await ev(`(function(){var r=document.querySelector('.img-col').getBoundingClientRect();return JSON.stringify({x:Math.round(r.x+r.width/2),y:Math.round(r.y+r.height/2)})})()`));
  await send('Input.dispatchMouseEvent',{type:'mouseMoved',x:b.x,y:b.y});
  await send('Input.dispatchMouseEvent',{type:'mousePressed',x:b.x,y:b.y,button:'left',buttons:1,clickCount:1});
  await sleep(80);
  await send('Input.dispatchMouseEvent',{type:'mouseReleased',x:b.x,y:b.y,button:'left',buttons:0,clickCount:1});
  await sleep(1200);
  console.log('  3) 真鼠标 ('+b.x+','+b.y+') -> ' + await ev(V));
  await close();
  const c2 = JSON.parse(await ev(`(function(){var r=document.querySelector('.img-col .label').getBoundingClientRect();return JSON.stringify({x:Math.round(r.x+r.width/2),y:Math.round(r.y+r.height/2)})})()`));
  await send('Input.dispatchMouseEvent',{type:'mouseMoved',x:c2.x,y:c2.y});
  await send('Input.dispatchMouseEvent',{type:'mousePressed',x:c2.x,y:c2.y,button:'left',buttons:1,clickCount:1});
  await sleep(80);
  await send('Input.dispatchMouseEvent',{type:'mouseReleased',x:c2.x,y:c2.y,button:'left',buttons:0,clickCount:1});
  await sleep(1200);
  console.log('  4) 真鼠标点角标 ('+c2.x+','+c2.y+') -> ' + await ev(V));
  ws.close(); child.kill();
})();
