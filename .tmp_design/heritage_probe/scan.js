const fs = require("fs"), vm = require("vm");
const ctx = vm.createContext({ window: {} });
const p = "C:/Users/lenovo/Desktop/heritage/";
for (const f of ["data.js", "sections.js"]) vm.runInContext(fs.readFileSync(p + f, "utf8"), ctx, { filename: f });
const items = ctx.window.FY_ITEMS, secs = ctx.window.FY_SECTIONS;
console.log("sections fields:", Object.keys(secs[0]).join(","));
console.log(secs.map(s => `${s.no}·${s.name} id=${s.id} items=${items.filter(i => i.sec === s.id).length} img=${s.img} en=${s.en} tone=${s.tone} pos=${s.pos} hook=${String(s.hook).slice(0, 20)} lead=${String(s.lead).length}`).join("\n"));
console.log("item fields:", Object.keys(items[0]).join(","));
console.log("total steps:", items.reduce((a, i) => a + i.steps.length, 0));
console.log("step fields:", [...new Set(items.flatMap(i => i.steps.flatMap(s => Object.keys(s))))].join(","));
console.log("histNode fields:", [...new Set(items.flatMap(i => (i.histNodes || []).flatMap(h => Object.keys(h))))].join(","));
console.log("chain sample:", JSON.stringify(items[0].chain));
console.log("video sample:", JSON.stringify(items[0].video));
console.log("peak:", [...new Set(items.map(i => i.peak))].join(" | "));
console.log("her:", [...new Set(items.map(i => i.her))].join(" / "));
console.log("no inheritor:", items.filter(i => !i.inheritor).length, "of", items.length);
console.log("no video:", items.filter(i => !i.video).length);
console.log("no histNodes:", items.filter(i => !(i.histNodes || []).length).length);
console.log("img files:", [...new Set(items.map(i => i.img))].length, "unique;", items.map(i => i.img).sort().slice(0, 2).join(), "...", items.map(i => i.img).sort().slice(-2).join());
console.log("sections img:", secs.map(s => s.img).join(" "));
